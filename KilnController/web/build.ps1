# Builds the React page and compresses it into ../webpage.h so the sketch can serve it.
# Run this after changing anything in web/src, then upload the sketch again:
#   powershell -ExecutionPolicy Bypass -File web\build.ps1
# The first time, run `npm install` in the web folder.

$ErrorActionPreference = "Stop"
$target = Join-Path (Split-Path $PSScriptRoot -Parent) "webpage.h"

Push-Location $PSScriptRoot
try {
    if (-not (Test-Path "node_modules")) { npm install --no-fund --no-audit; if ($LASTEXITCODE) { throw "npm install failed" } }
    npm run build
    if ($LASTEXITCODE) { throw "npm run build failed" }
} finally {
    Pop-Location
}

$source = Join-Path $PSScriptRoot "dist\index.html"
$bytes = [System.IO.File]::ReadAllBytes($source)
$memory = New-Object System.IO.MemoryStream
$gzip = New-Object System.IO.Compression.GZipStream($memory, [System.IO.Compression.CompressionLevel]::Optimal)
$gzip.Write($bytes, 0, $bytes.Length)
$gzip.Close()
$compressed = $memory.ToArray()

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by web/build.ps1 from the React app in web/src. Don't edit by hand.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("const size_t KILN_PAGE_GZ_LEN = $($compressed.Length);")
[void]$sb.AppendLine("const uint8_t KILN_PAGE_GZ[] = {")
for ($i = 0; $i -lt $compressed.Length; $i += 20) {
    $end = [Math]::Min($i + 20, $compressed.Length) - 1
    $line = ($compressed[$i..$end] | ForEach-Object { "0x{0:x2}" -f $_ }) -join ","
    [void]$sb.AppendLine("  $line,")
}
[void]$sb.AppendLine("};")

[System.IO.File]::WriteAllText($target, $sb.ToString())
Write-Host "webpage.h written: $($bytes.Length) bytes -> $($compressed.Length) bytes gzipped"
